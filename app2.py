import folium
import streamlit as st
from streamlit_folium import st_folium

# Configure Streamlit page layout
st.set_page_config(
    page_title="Mangrove Health & Restoration Monitor",
    page_icon="🌿",
    layout="wide",
)

st.title("🌿 Mangrove Health & Restoration Monitor")
st.markdown(
    "**Early detection of mangrove degradation and restoration prioritization** using Sentinel-2, Tanager hyperspectral data, and Global Mangrove Watch baselines."
)

# Sidebar controls for filters and thresholds
st.sidebar.header("Monitoring Controls")
selected_date = st.sidebar.date_input("Select Monitoring Date", value=None)
layer_toggle = st.sidebar.multiselect(
    "Display Layers",
    options=[
        "Green: Healthy Mangrove",
        "Yellow: Possible Stress",
        "Red: Degraded / Change Area",
        "Blue: Restoration Priority",
    ],
    default=[
        "Green: Healthy Mangrove",
        "Yellow: Possible Stress",
        "Red: Degraded / Change Area",
        "Blue: Restoration Priority",
    ],
)

st.sidebar.markdown("---")
st.sidebar.info(
    "Tip: In production, these layers are dynamically generated by computing NDVI/NDCI indices from Sentinel-2/Tanager against Global Mangrove Watch baselines."
)

# Initialize map centered on a coastal sample site (e.g., Arabian Gulf / Mangrove ecosystem)
m = folium.Map(location=[24.4539, 54.3773], zoom_start=12, tiles="CartoDB positron")

# Mock geospatial polygons/markers representing the categories for demonstration
# (In your production app, you will load these from your GeoJSON or raster polygon outputs)

if "Green: Healthy Mangrove" in layer_toggle:
  # Healthy Mangrove Polygon sample
  folium.Polygon(
      locations=[
          [24.46, 54.37],
          [24.47, 54.38],
          [24.45, 54.39],
          [24.44, 54.37],
      ],
      color="green",
      fill=True,
      fill_color="green",
      fill_opacity=0.6,
      popup="Healthy Mangrove (Stable Canopy)",
  ).add_to(m)

if "Yellow: Possible Stress" in layer_toggle:
  # Stress Area Polygon sample
  folium.Polygon(
      locations=[
          [24.47, 54.39],
          [24.48, 54.40],
          [24.46, 54.41],
      ],
      color="orange",
      fill=True,
      fill_color="yellow",
      fill_opacity=0.6,
      popup="Possible Stress Detected (Drop in moisture/chlorophyll)",
  ).add_to(m)

if "Red: Degraded / Change Area" in layer_toggle:
  # Degraded Area Polygon sample
  folium.Polygon(
      locations=[
          [24.43, 54.35],
          [24.44, 54.36],
          [24.42, 54.36],
      ],
      color="darkred",
      fill=True,
      fill_color="red",
      fill_opacity=0.6,
      popup="Degraded / Canopy Loss Area",
  ).add_to(m)

if "Blue: Restoration Priority" in layer_toggle:
  # Restoration Priority Polygon sample
  folium.Polygon(
      locations=[
          [24.41, 54.33],
          [24.42, 54.34],
          [24.40, 54.35],
      ],
      color="blue",
      fill=True,
      fill_color="blue",
      fill_opacity=0.5,
      popup="Restoration Priority Zone (Favorable tidal connectivity)",
  ).add_to(m)

# Custom HTML Map Legend
legend_html = """
    <div style="position: fixed; 
                bottom: 30px; left: 30px; width: 240px; height: 160px; 
                background-color: white; z-index:9999; font-size:14px;
                border:2px solid grey; border-radius: 6px; padding: 10px;">
      <b>Mangrove Health Legend</b><br>
      <i style="background:green; width:14px; height:14px; display:inline-block; margin-right:5px;"></i> Green: Healthy Mangrove<br>
      <i style="background:yellow; width:14px; height:14px; display:inline-block; margin-right:5px;"></i> Yellow: Possible Stress<br>
      <i style="background:red; width:14px; height:14px; display:inline-block; margin-right:5px;"></i> Red: Degraded / Change<br>
      <i style="background:blue; width:14px; height:14px; display:inline-block; margin-right:5px;"></i> Blue: Restoration Priority<br>
    </div>
"""
m.get_root().html.add_child(folium.Element(legend_html))

# Render the interactive map inside Streamlit
st_data = st_folium(m, width=1100, height=600)

# Summary statistics section below the map
col1, col2, col3, col4 = st.columns(4)
col1.metric("Healthy Cover", "1,245 ha", "+2.1%")
col2.metric("Stressed Area", "180 ha", "-5.4%")
col3.metric("Degraded Loss", "45 ha", "+1.2%")
col4.metric("Restoration Potential", "320 ha", "Priority Tier 1")
